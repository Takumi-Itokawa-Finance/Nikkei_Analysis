cells.append(md([
    "## 2. FFT と振幅スペクトル / FFT & Amplitude Spectrum\n",
    "\n",
    "### フーリエ定理 / Fourier's Theorem\n",
    "\n",
    "任意の時系列 $x(t)$ はサイン波の重ね合わせで表現できます：\n",
    "\n",
    "$$x(t) \\approx \\bar{x} + \\sum_{k} A_k \\cos\\bigl(2\\pi f_k\\, t + \\varphi_k\\bigr)$$\n",
    "\n",
    "| 記号 | 意味 | 単位 |\n",
    "|------|------|------|\n",
    "| $f_k = k/N$ | 周波数 | サイクル / 営業日 |\n",
    "| $A_k = 2|X_k|/N$ | 振幅（成分の強さ） | JPY |\n",
    "| $\\varphi_k = \\angle X_k$ | 位相（波のずれ） | ラジアン |\n",
    "\n",
    "### デトレンドの必要性\n",
    "\n",
    "株価は長期的な上昇トレンドを持つため、まず **線形トレンドを除去** します。  \n",
    "こうすることで FFT がトレンドではなく **周期的な変動成分** を捉えるようになります。\n",
    "\n",
    "### 手順\n",
    "\n",
    "1. `np.polyfit(t, prices, 1)` で線形トレンドを推定\n",
    "2. 残差（デトレンド系列）に `np.fft.rfft` を適用\n",
    "3. 各周波数の振幅 $A_k = 2|X_k|/N$ を計算\n",
]))

cells.append(code([
    "# 1. Linear detrend\n",
    "t          = np.arange(N)\n",
    "trend_coef = np.polyfit(t, prices, 1)\n",
    "trend      = np.polyval(trend_coef, t)\n",
    "detrended  = prices - trend\n",
    "\n",
    "# 2. FFT of detrended series (rfft: efficient for real input)\n",
    "fft_vals = np.fft.rfft(detrended)\n",
    "freqs    = np.fft.rfftfreq(N)     # unit: cycles per trading day\n",
    "amps     = np.abs(fft_vals)       # raw FFT magnitudes\n",
    "phases   = np.angle(fft_vals)     # phase angles in radians\n",
    "\n",
    "# 3. One-sided amplitude: A_k = 2|X_k|/N\n",
    "onesided = amps / N\n",
    "onesided[1:-1] *= 2\n",
    "\n",
    "# 4. Period in trading days\n",
    "with np.errstate(divide='ignore'):\n",
    "    periods = np.where(freqs > 0, 1.0 / freqs, np.inf)\n",
    "\n",
    "print(f'FFT components   : {len(fft_vals)}')\n",
    "print(f'Nyquist period   : 2 trading days (shortest detectable cycle)')\n",
    "print(f'Longest period   : {N} days = {N/252:.1f} years')\n",
]))

